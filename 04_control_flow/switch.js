const month = "november"

switch (month) {
    case "september":
        console.log("september");
        break;

    case "october":
        console.log("october");
        break;
    case "november":
        console.log("november");
        break;
    case "december":
        console.log("december");
        break;

    default:
        console.log("default case match");
        break;
}